"""Parses Treas. Reg. 1.401(a)(9)-9 (eCFR XML) into the three RMD life-expectancy tables.
Run: python3 scripts/data/build_rmd_tables.py  → src/data/generated/rmd-tables.ts
"""
import json, pathlib, re
import xml.etree.ElementTree as ET

src = pathlib.Path("data-raw/irs/ecfr-1.401a9-9.xml").read_text()
root = ET.fromstring(src)
tables = root.iter("TABLE")
tables = list(root.iter("TABLE"))

def txt(el):
    return "".join(el.itertext()).strip()

def age(s):
    s = s.strip()
    return 120 if s.startswith("120") else int(s)

def rows_of(t):
    out = []
    for tr in t.iter("TR"):
        cells = [txt(c) for c in tr if c.tag in ("TD", "TH")]
        if cells and re.fullmatch(r"\d+|120\+?", cells[0].strip()):
            out.append(cells)
    return out

single = {age(r[0]): float(r[1]) for r in rows_of(tables[0])}
uniform = {age(r[0]): float(r[1]) for r in rows_of(tables[1])}

joint = {}
for t in tables[2:27]:
    head = None
    for tr in t.iter("TR"):
        ths = [txt(c) for c in tr if c.tag == "TH"]
        if ths and ths[0].lower().startswith("age"):
            head = [age(h) for h in ths[1:] if h.strip()]
            break
    if head is None:
        continue
    for r in rows_of(t):
        a = age(r[0])
        for j, colage in enumerate(head):
            if j + 1 < len(r) and r[j + 1].strip():
                joint[(a, colage)] = float(r[j + 1])

# Regulation has one blank cell at (19,35): fill from its symmetric twin (35,19).
if (19, 35) not in joint and (35, 19) in joint:
    joint[(19, 35)] = joint[(35, 19)]

missing = [(a, b) for a in range(121) for b in range(121) if (a, b) not in joint]
assert len(single) == 121, len(single)
assert len(uniform) == 49, len(uniform)
assert not missing, missing[:10]
# spot checks from the research (eCFR)
for (a, b, v) in [(0, 0, 91.9), (75, 64, 25.3), (80, 65, 23.8), (35, 19, 68.0), (120, 120, 1.0)]:
    assert joint[(a, b)] == v, (a, b, joint[(a, b)], v)
assert uniform[72] == 27.4 and uniform[73] == 26.5 and uniform[120] == 2.0
assert single[0] == 84.6 and single[120] == 1.0

grid = [[joint[(a, b)] for b in range(121)] for a in range(121)]
out = pathlib.Path("src/data/generated/rmd-tables.ts")
out.write_text(
    "// GENERATED by scripts/data/build_rmd_tables.py from Treas. Reg. §1.401(a)(9)-9 (eCFR, as of 2026-10-01). Do not edit.\n"
    "// Tables apply to distribution calendar years beginning on or after January 1, 2022.\n"
    "/** Uniform Lifetime Table — key: age (120 = 120 and older) → distribution period. */\n"
    f"export const UNIFORM_LIFETIME: Record<number, number> = {json.dumps(uniform)};\n"
    "/** Single Life Table — key: age (120 = 120 and older) → life expectancy. */\n"
    f"export const SINGLE_LIFE: Record<number, number> = {json.dumps(single)};\n"
    "/** Joint and Last Survivor Table — JOINT_LIFE[ownerAge][spouseAge], ages 0..120 (120 = 120+). */\n"
    f"export const JOINT_LIFE: number[][] = {json.dumps(grid, separators=(',', ':'))};\n"
)
print("single", len(single), "uniform", len(uniform), "joint cells", len(joint), "bytes", out.stat().st_size)
