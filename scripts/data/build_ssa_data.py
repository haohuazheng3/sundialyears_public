"""Builds typed data modules from raw SSA OACT files in data-raw/ssa (fetched by scripts/tools/fetch-ssa.mjs).
Run: python3 scripts/data/build_ssa_data.py   — outputs src/data/generated/*.ts and public/data/cohort-qx-tr2026.json
"""
import csv, html, json, re, pathlib

RAW = pathlib.Path("data-raw/ssa")
OUT = pathlib.Path("src/data/generated")
PUB = pathlib.Path("public/data")

def table_cells(name):
    s = (RAW / name).read_text()
    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", s, re.S)
    return [[html.unescape(re.sub(r"<[^>]+>", "", c)).strip() for c in re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r, re.S)] for r in rows]

def num(x):
    return float(x.replace(",", "").replace("$", "").strip())

header = '// GENERATED by scripts/data/build_ssa_data.py from {src} — do not edit by hand.\n'

# AWI 1951–latest
awi = {}
for c in table_cells("AWI.html"):
    if len(c) == 2 and re.fullmatch(r"\d{4}", c[0]):
        awi[int(c[0])] = num(c[1])
(OUT / "awi.ts").write_text(header.format(src="https://www.ssa.gov/oact/cola/AWI.html") +
    "export const AWI: Record<number, number> = " + json.dumps(awi) + ";\nexport const AWI_LATEST_YEAR = " + str(max(awi)) + ";\n")

# Taxable maximum (contribution & benefit base)
cbb = {}
for c in table_cells("cbb.html"):
    if len(c) == 2 and re.fullmatch(r"\d{4}(-\d{2})?", c[0]):
        a = c[0]
        if "-" in a:
            y0, y1 = a.split("-"); y0 = int(y0); y1 = int(str(y0)[:2] + y1)
            for y in range(y0, y1 + 1): cbb[y] = num(c[1])
        else:
            cbb[int(a)] = num(c[1])
(OUT / "taxable-max.ts").write_text(header.format(src="https://www.ssa.gov/oact/cola/cbb.html") +
    "export const TAXABLE_MAX: Record<number, number> = " + json.dumps(cbb) + ";\n")

# COLA history (keyed by year the COLA took effect in December; first paid in January of year+1)
cola = {}
for c in table_cells("colaseries.html"):
    if len(c) == 2 and re.fullmatch(r"\d{4}(\s*a)?", c[0].replace("\xa0", " ")) and re.fullmatch(r"\d+\.\d", c[1]):
        cola[int(c[0][:4])] = float(c[1])
(OUT / "cola-history.ts").write_text(header.format(src="https://www.ssa.gov/oact/cola/colaseries.html") +
    "/** COLA % keyed by the December it took effect (paid starting the following January). 1975–1982 were June COLAs. */\n"
    "export const COLA_BY_EFFECTIVE_YEAR: Record<number, number> = " + json.dumps(cola) + ";\n")

# 2023 period life table (as used in the 2026 Trustees Report)
plt = []
for c in table_cells("table4c6.html"):
    if len(c) == 7 and re.fullmatch(r"\d+", c[0]):
        plt.append([int(c[0]), num(c[1]), num(c[2]), num(c[3]), num(c[4]), num(c[5]), num(c[6])])
(OUT / "period-life-table.ts").write_text(header.format(src="https://www.ssa.gov/oact/STATS/table4c6.html (2023 period table, 2026 Trustees Report)") +
    "/** [age, maleQ, maleLives, maleLifeExpectancy, femaleQ, femaleLives, femaleLifeExpectancy] */\n"
    "export const PERIOD_LIFE_TABLE_YEAR = 2023;\n"
    "export const PERIOD_LIFE_TABLE: [number, number, number, number, number, number, number][] = " + json.dumps(plt) + ";\n")

# Cohort q(x) by birth year (TR2026 intermediate), ages 50–119, birth years 1935–1980
def cohort(sex):
    out = {}
    with open(RAW / f"CohLifeTables_{sex}_Alt2_TR2026.csv") as f:
        for row in csv.reader(f):
            if len(row) < 8 or not row[0].strip().isdigit(): continue
            by, x, q = int(row[0]), int(row[1]), float(row[2])
            if 1935 <= by <= 1980 and x >= 50:
                out.setdefault(by, [None] * 70)[x - 50] = q
    for by, arr in out.items():
        assert all(v is not None for v in arr), (sex, by)
    return out
coh = {"source": "SSA OACT CohLifeTables_[M|F]_Alt2_TR2026.csv (2026 Trustees Report, intermediate assumptions)",
       "ages": [50, 119], "male": cohort("M"), "female": cohort("F")}
PUB.mkdir(parents=True, exist_ok=True)
(PUB / "cohort-qx-tr2026.json").write_text(json.dumps(coh, separators=(",", ":")))
print("AWI", min(awi), max(awi), "| CBB", min(cbb), max(cbb), "| COLA", min(cola), max(cola), cola[max(cola)], "| period rows", len(plt), "| cohort years", len(coh["male"]))
